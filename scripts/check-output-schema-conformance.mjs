// Phase 11 (R11.1 / CCR-Output-Schema): build-time guard that every tool
// `outputSchema` literal is a valid JSON Schema (draft-07).
//
// Mirrors packages/mcp-server/scripts/validate-tool-schemas.mjs (which validates
// inputSchema), but for the NEW `outputSchema:` field added in Phase 11. It
// enumerates every compiled tool class in `packages/mcp-server/dist/tools/`,
// calls getToolDefinitions(), and for every def that declares an `outputSchema`,
// compiles it through Ajv. If any outputSchema fails to compile, the build fails
// with a list of offenders.
//
// Per-tool structuredContent ↔ outputSchema runtime conformance is covered by the
// vitest suite (packages/mcp-server/src/__tests__/output-schema-conformance.test.ts);
// this static check is the on-build gate that the SCHEMAS themselves are well-formed.
//
// Runs at the END of `build:server` (after the mcp-server workspace build emits
// dist/) — NOT before it (dist/tools would be stale/absent).

import { readdirSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import Ajv from 'ajv';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TOOLS_DIR = path.resolve(HERE, '..', 'packages', 'mcp-server', 'dist', 'tools');

/** Recursively collect compiled tool .js files (incl. dist/tools/modules/** subtree —
 *  module umbrella tools like module-matt also declare outputSchema). */
function walkJs(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walkJs(full));
    else if (e.isFile() && e.name.endsWith('.js')) out.push(full);
  }
  return out;
}

const stubLogger = {
  child: () => stubLogger,
  info: () => {},
  warn: () => {},
  error: () => {},
  debug: () => {},
};
const stubFoundryClient = {};

// strict:false — outputSchemas are GENERATED by zodToJsonSchema (they carry
// $schema / additionalProperties / $ref+definitions that Ajv strict mode flags as
// pedantic warnings). The goal here is "valid, compilable draft-07", not strict-
// mode lint. allowUnionTypes mirrors the inputSchema validator (nullable → unions).
const ajv = new Ajv({ strict: false, allowUnionTypes: true, allErrors: true });

async function collectToolClasses(fullPath) {
  const url = pathToFileURL(fullPath).href;
  const mod = await import(url);
  const classes = [];
  for (const exported of Object.values(mod)) {
    if (typeof exported !== 'function') continue;
    if (!exported.prototype || typeof exported.prototype.getToolDefinitions !== 'function') continue;
    classes.push(exported);
  }
  return classes;
}

async function main() {
  let files;
  try {
    files = walkJs(TOOLS_DIR);
  } catch (e) {
    console.error(`[check-output-schema-conformance] cannot read ${TOOLS_DIR} — did the mcp-server build run first? ${e?.message ?? e}`);
    process.exit(1);
  }

  const errors = [];
  let outputSchemaCount = 0;

  for (const file of files) {
    let classes;
    try {
      classes = await collectToolClasses(file);
    } catch (e) {
      errors.push(`${file}: import failed — ${e?.message ?? e}`);
      continue;
    }
    for (const ClassCtor of classes) {
      let instance;
      try {
        instance = new ClassCtor({ foundryClient: stubFoundryClient, logger: stubLogger });
      } catch (e) {
        errors.push(`${file} / ${ClassCtor.name}: construction failed — ${e?.message ?? e}`);
        continue;
      }
      let toolDefs;
      try {
        toolDefs = instance.getToolDefinitions();
      } catch (e) {
        errors.push(`${file} / ${ClassCtor.name}: getToolDefinitions threw — ${e?.message ?? e}`);
        continue;
      }
      for (const def of toolDefs ?? []) {
        if (!def || def.outputSchema === undefined) continue;
        outputSchemaCount++;
        try {
          ajv.compile(def.outputSchema);
        } catch (e) {
          errors.push(`tool "${def?.name ?? '<anon>'}" (${file}): invalid outputSchema — ${e?.message ?? e}`);
        }
      }
    }
  }

  if (errors.length > 0) {
    console.error(`\n[check-output-schema-conformance] ${errors.length} offender(s):\n`);
    for (const err of errors) console.error(`  - ${err}`);
    console.error(`\nTotal outputSchema objects scanned: ${outputSchemaCount}`);
    process.exit(1);
  }

  if (outputSchemaCount === 0) {
    console.error('[check-output-schema-conformance] FAIL — zero outputSchema objects found; expected ≥18 (Phase 11 R11.1).');
    process.exit(1);
  }

  console.log(`[check-output-schema-conformance] OK — ${outputSchemaCount} tool outputSchema objects validated (ajv draft-07).`);
}

await main();
